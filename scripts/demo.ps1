# Offline demo for Windows (PowerShell 5.1+) – same behaviour as scripts/demo.sh.
# Only Docker Desktop is required – no Node/pnpm, no bash.
#
#   powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 start    build, start, migrate, seed once, print URLs
#   powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 stop     stop all containers (data is kept)
#   powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 seed     reset the demo people/trips (@demo.test)
#   powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 unlock   clear the sign-in limits ("Bitte warte kurz …")
#   powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 reset    delete EVERYTHING (database, mails)
#   powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 status   show containers and URLs
#   powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 logs     follow the app log (Ctrl+C to quit)
#
# Secrets: on the first start .env.demo is generated locally with random values. It is
# ignored by git (.gitignore: .env.*) and must never be committed.
param([string]$Command = "start")

$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")

$EnvFile = ".env.demo"
$ComposeArgs = @("compose", "-f", "docker/compose.demo.yml", "--env-file", $EnvFile)
$Port = 3000
$MailpitPort = 8025
$Script:DemoUrl = ""
$Script:MailUrl = ""

function Say([string]$text) { Write-Host ""; Write-Host "==> $text" -ForegroundColor Cyan }
function Fail([string]$text) {
  Write-Host ""
  Write-Host "FEHLER: $text" -ForegroundColor Red
  exit 1
}

function New-Secret([int]$bytes = 32) {
  $buffer = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
  return [Convert]::ToBase64String($buffer)
}

function Get-EnvValue([string]$key) {
  if (-not (Test-Path $EnvFile)) { return "" }
  $line = Get-Content $EnvFile | Where-Object { $_ -match "^$key=" } | Select-Object -Last 1
  if (-not $line) { return "" }
  return ($line.Substring($key.Length + 1)).Trim('"')
}

function Test-Docker {
  if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Fail "Docker ist nicht installiert. Bitte Docker Desktop installieren: https://www.docker.com/products/docker-desktop/"
  }
  & docker info *> $null
  if ($LASTEXITCODE -ne 0) {
    Fail "Docker läuft nicht. Bitte Docker Desktop starten (Wal-Symbol unten rechts in der Taskleiste), kurz warten und den Befehl wiederholen."
  }
  & docker compose version *> $null
  if ($LASTEXITCODE -ne 0) { Fail "'docker compose' fehlt. Bitte Docker Desktop aktualisieren." }
}

# Compose needs these variables even to stop/remove containers; when .env.demo is missing
# placeholders are enough for "down".
function Invoke-ComposeWithoutEnv {
  $env:POSTGRES_PASSWORD = "unused"
  $env:BETTER_AUTH_SECRET = "unused-unused-unused-unused-unused"
  & docker compose -f docker/compose.demo.yml @args
}

function New-EnvFile {
  if (Test-Path $EnvFile) { return }
  Say "Erste Einrichtung: lege $EnvFile mit zufälligen lokalen Schlüsseln an"
  $pw = ((New-Secret 32) -replace "[^A-Za-z0-9]", "")
  if ($pw.Length -gt 24) { $pw = $pw.Substring(0, 24) }
  $lines = @(
    "# Offline demo – generated by scripts/demo.ps1 on $(Get-Date -Format yyyy-MM-dd). Local only, never commit.",
    "APP_ENV=demo",
    "BETTER_AUTH_SECRET=$(New-Secret 32)",
    "POSTGRES_PASSWORD=$pw",
    "# 0.0.0.0 = reachable from phones in the same (trusted!) WLAN · 127.0.0.1 = laptop only",
    "DEMO_BIND_ADDRESS=0.0.0.0",
    "# Optional: fixed address for phones (e.g. 192.168.178.20). Empty = detected on every start.",
    "DEMO_HOST="
  )
  # UTF-8 without BOM and LF line endings, like the bash version.
  [System.IO.File]::WriteAllText((Join-Path (Get-Location) $EnvFile), (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding $false))
}

# LAN IPv4 address of the adapter with the default gateway (WLAN/Ethernet), empty if none.
function Get-LanIp {
  try {
    $cfg = Get-NetIPConfiguration -ErrorAction Stop |
      Where-Object { $_.IPv4DefaultGateway -ne $null -and $_.NetAdapter.Status -eq "Up" } |
      Select-Object -First 1
    if ($cfg -and $cfg.IPv4Address) { return ($cfg.IPv4Address | Select-Object -First 1).IPAddress }
  } catch { }
  return ""
}

function Set-Urls {
  $bind = Get-EnvValue "DEMO_BIND_ADDRESS"
  $hostName = Get-EnvValue "DEMO_HOST"
  if ($bind -eq "127.0.0.1") {
    $hostName = "localhost"
  } elseif (-not $hostName) {
    $hostName = Get-LanIp
    if (-not $hostName) { $hostName = "localhost" }
  }
  $Script:DemoUrl = "http://${hostName}:$Port"
  $Script:MailUrl = "http://${hostName}:$MailpitPort"
  $env:APP_URL = $Script:DemoUrl
  $env:BETTER_AUTH_URL = $Script:DemoUrl
  $env:AUTH_TRUSTED_ORIGINS = "http://localhost:$Port,http://127.0.0.1:$Port"
}

function Test-PortInUse([int]$p) {
  # Our own demo containers may already hold the ports – that is fine.
  $running = & docker @ComposeArgs ps --status running -q 2>$null
  if ($running) { return $false }
  try {
    $conn = Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue
    return [bool]$conn
  } catch {
    return $false
  }
}

function Wait-ForApp {
  Write-Host -NoNewline "Warte auf die App "
  for ($i = 0; $i -lt 90; $i++) {
    try {
      $r = Invoke-WebRequest -UseBasicParsing -TimeoutSec 5 "http://localhost:$Port/api/health"
      if ($r.StatusCode -eq 200) { Write-Host " bereit."; return }
    } catch { }
    Write-Host -NoNewline "."
    Start-Sleep -Seconds 2
  }
  Write-Host ""
  Fail "Die App antwortet nicht. Log ansehen mit: powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 logs"
}

# SQL goes in via stdin – avoids PowerShell's quoting quirks with native programs.
function Invoke-Sql([string]$sql, [switch]$Tuples) {
  $extra = @()
  if ($Tuples) { $extra = @("-tA") }
  $out = $sql | & docker @ComposeArgs exec -T db psql -U app -d wirwollenweg -q @extra 2>$null
  return $out
}

function Get-DemoPeopleCount {
  $out = Invoke-Sql "select count(*) from ""user"" where email like '%@demo.test';" -Tuples
  return ("$out").Trim()
}

function Show-Urls {
  if ((Get-EnvValue "DEMO_BIND_ADDRESS") -eq "127.0.0.1") {
    $phone = "aus – nur am Laptop erreichbar (DEMO_BIND_ADDRESS=127.0.0.1)"
  } elseif ($Script:DemoUrl -like "http://localhost*") {
    $phone = "nicht möglich – keine WLAN-Adresse gefunden"
  } else {
    $phone = "$($Script:DemoUrl)`n  Codes am Handy: $($Script:MailUrl)"
  }
  Write-Host ""
  Write-Host "------------------------------------------------------------------"
  Write-Host "  Wir wollen weg – Demo läuft" -ForegroundColor Green
  Write-Host ""
  Write-Host "  Am Laptop:      http://localhost:$Port"
  Write-Host "  Login-Codes:    http://localhost:$MailpitPort   (Mailpit – hier kommen alle Mails an)"
  Write-Host ""
  Write-Host "  Handy (gleiches WLAN):"
  Write-Host "                  $phone"
  Write-Host ""
  Write-Host "  Demo-Login:     anna@demo.test (Code aus Mailpit)"
  Write-Host "  Stoppen:        powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 stop"
  Write-Host "------------------------------------------------------------------"
}

# The database volume outlives .env.demo – set the password to the current value on every start.
function Sync-DbPassword {
  $pw = Get-EnvValue "POSTGRES_PASSWORD"
  if ($pw -notmatch "^[A-Za-z0-9]+$") { Fail "POSTGRES_PASSWORD in $EnvFile darf nur Buchstaben und Ziffern enthalten." }
  Invoke-Sql "alter user app with password '$pw';" | Out-Null
}

function Clear-Limits {
  if ((Get-EnvValue "APP_ENV") -ne "demo") { Fail "unlock ist nur für die Demo gedacht (APP_ENV=demo)." }
  Invoke-Sql "delete from auth_attempt; delete from rate_limit; delete from rate_limit_event;" | Out-Null
}

function Require-EnvFile {
  if (-not (Test-Path $EnvFile)) {
    Fail "Die Demo wurde noch nie gestartet. Erst: powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 start"
  }
}

function Start-Demo {
  Test-Docker
  New-EnvFile
  Set-Urls
  foreach ($p in @($Port, $MailpitPort)) {
    if (Test-PortInUse $p) {
      Fail "Port $p ist schon belegt (läuft noch ein anderes Programm oder eine alte Demo?). Siehe Anleitung, Abschnitt Fehlerbehebung."
    }
  }
  Say "Baue und starte die Demo (beim ersten Mal 5–10 Minuten)"
  & docker @ComposeArgs up -d --build
  if ($LASTEXITCODE -ne 0) {
    Fail "Bauen/Starten hat nicht geklappt (Meldungen oben). Internet und Docker prüfen und den Befehl wiederholen – Anleitung, Abschnitt 4.7."
  }
  Say "Datenbank vorbereiten"
  Start-Sleep -Seconds 3
  Sync-DbPassword
  & docker @ComposeArgs run --rm tools pnpm db:migrate
  if ($LASTEXITCODE -ne 0) {
    Fail "Die Datenbank konnte nicht eingerichtet werden (Meldungen oben). Befehl wiederholen – sonst die letzten Zeilen ans Team schicken."
  }
  if ((Get-DemoPeopleCount) -eq "0") {
    Say "Demo-Daten einspielen (Anna, Ben, Carla … und ihre Reisen)"
    & docker @ComposeArgs run --rm tools pnpm db:seed:demo | Out-Null
  }
  Wait-ForApp
  Show-Urls
}

switch ($Command.ToLower()) {
  { $_ -in @("start", "up") } { Start-Demo; break }
  { $_ -in @("stop", "down") } {
    Test-Docker
    Say "Stoppe die Demo (Daten bleiben erhalten)"
    if (Test-Path $EnvFile) { Set-Urls; & docker @ComposeArgs down } else { Invoke-ComposeWithoutEnv down }
    break
  }
  "seed" {
    Test-Docker; Require-EnvFile; Set-Urls
    Say "Setze die Demo-Personen und -Reisen zurück"
    & docker @ComposeArgs run --rm tools pnpm db:seed:demo | Out-Null
    Clear-Limits
    Write-Host "Fertig. Alle Personen @demo.test (auch selbst angelegte) und ihre Reisen sind wie neu."
    break
  }
  "unlock" {
    Test-Docker; Require-EnvFile; Set-Urls; Clear-Limits
    Write-Host "Anmelde-Sperren aufgehoben – du kannst sofort neue Codes anfordern."
    break
  }
  "reset" {
    Test-Docker
    Say "Lösche die Demo komplett (Datenbank und Mails)"
    Invoke-ComposeWithoutEnv down -v --remove-orphans
    Write-Host "Fertig. Neu starten mit: powershell -ExecutionPolicy Bypass -File scripts\demo.ps1 start"
    break
  }
  "status" { Test-Docker; Require-EnvFile; Set-Urls; & docker @ComposeArgs ps; Show-Urls; break }
  "logs" { Test-Docker; Require-EnvFile; Set-Urls; & docker @ComposeArgs logs -f --tail 100 app; break }
  { $_ -in @("help", "-h", "--help") } {
    Get-Content $PSCommandPath | Select-Object -Skip 1 -First 12 | ForEach-Object { $_ -replace "^# ?", "" }
    break
  }
  default { Fail "Unbekannter Befehl '$Command'. Möglich: start, stop, seed, unlock, reset, status, logs" }
}

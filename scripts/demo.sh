#!/usr/bin/env bash
# Offline demo for the client (docs/ops/demo-anleitung.md, deployment.md §0).
# Only Docker is required – no Node/pnpm on the laptop.
#
#   bash scripts/demo.sh            same as "start"
#   bash scripts/demo.sh start      build (first time), start, migrate, seed demo data once, print URLs
#   bash scripts/demo.sh stop       stop all containers (data is kept)
#   bash scripts/demo.sh seed       reset the demo people/trips (@demo.test) to the original state
#   bash scripts/demo.sh unlock     clear the sign-in limits ("Bitte warte kurz …") – demo only
#   bash scripts/demo.sh reset      delete EVERYTHING (database, mails) – next start begins fresh
#   bash scripts/demo.sh status     show containers and URLs
#   bash scripts/demo.sh logs       follow the app log (Ctrl+C to quit)
#
# Secrets: on the first start .env.demo is generated locally with random values. It is
# ignored by git (.gitignore: .env.*) and must never be committed.
set -euo pipefail

cd "$(dirname "$0")/.."

ENV_FILE=.env.demo
COMPOSE=(docker compose -f docker/compose.demo.yml --env-file "$ENV_FILE")
PORT=3000
MAILPIT_PORT=8025

say() { printf '\n==> %s\n' "$*"; }
fail() {
  printf '\nFEHLER: %s\n' "$*" >&2
  exit 1
}

random_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 32 | tr -d '\n'
  else
    head -c 32 /dev/urandom | base64 | tr -d '\n'
  fi
}

# Value of KEY in .env.demo (last occurrence, quotes stripped), empty if missing.
env_value() {
  [ -f "$ENV_FILE" ] || return 0
  grep -E "^$1=" "$ENV_FILE" | tail -n 1 | cut -d= -f2- | sed -e 's/^"//' -e 's/"$//' || true
}

check_docker() {
  command -v docker >/dev/null 2>&1 ||
    fail "Docker ist nicht installiert. Bitte Docker Desktop installieren: https://www.docker.com/products/docker-desktop/"
  docker info >/dev/null 2>&1 ||
    fail "Docker läuft nicht. Bitte Docker Desktop starten (Wal-Symbol in der Menüleiste) und den Befehl wiederholen."
  docker compose version >/dev/null 2>&1 ||
    fail "'docker compose' fehlt. Bitte Docker Desktop aktualisieren."
}

# Compose needs these variables even to stop/remove containers; when .env.demo is missing
# (deleted, fresh ZIP) placeholders are enough for "down".
compose_without_env() {
  POSTGRES_PASSWORD=unused BETTER_AUTH_SECRET=unused-unused-unused-unused-unused \
    docker compose -f docker/compose.demo.yml "$@"
}

create_env_file() {
  [ -f "$ENV_FILE" ] && return 0
  say "Erste Einrichtung: lege $ENV_FILE mit zufälligen lokalen Schlüsseln an"
  umask 077
  cat >"$ENV_FILE" <<EOF
# Offline demo – generated by scripts/demo.sh on $(date +%Y-%m-%d). Local only, never commit.
APP_ENV=demo
BETTER_AUTH_SECRET=$(random_secret)
POSTGRES_PASSWORD=$(random_secret | tr -dc "A-Za-z0-9" | cut -c1-24)
# 0.0.0.0 = reachable from phones in the same (trusted!) WLAN · 127.0.0.1 = laptop only
DEMO_BIND_ADDRESS=0.0.0.0
# Optional: fixed address for phones (e.g. 192.168.178.20). Empty = detected on every start.
DEMO_HOST=
EOF
}

# LAN IPv4 address of this computer (macOS + Linux), empty if none.
detect_lan_ip() {
  local ip="" iface=""
  if command -v ipconfig >/dev/null 2>&1 && [ "$(uname)" = "Darwin" ]; then
    iface=$(route -n get default 2>/dev/null | awk '/interface:/ {print $2}' || true)
    for candidate in $iface en0 en1; do
      ip=$(ipconfig getifaddr "$candidate" 2>/dev/null || true)
      [ -n "$ip" ] && break
    done
  elif command -v ip >/dev/null 2>&1; then
    ip=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i < NF; i++) if ($i == "src") print $(i + 1)}' | head -n 1 || true)
  fi
  if [ -z "$ip" ] && command -v hostname >/dev/null 2>&1; then
    ip=$(hostname -I 2>/dev/null | awk '{print $1}' || true)
  fi
  printf '%s' "$ip"
}

# Public address used in mails and invite links. Phones need the LAN address; the laptop
# itself may use localhost as well (allowed via AUTH_TRUSTED_ORIGINS).
configure_urls() {
  local bind host
  bind=$(env_value DEMO_BIND_ADDRESS)
  host=$(env_value DEMO_HOST)
  if [ "$bind" = "127.0.0.1" ]; then
    host=localhost
  elif [ -z "$host" ]; then
    host=$(detect_lan_ip)
    [ -n "$host" ] || host=localhost
  fi
  DEMO_URL="http://$host:$PORT"
  MAIL_URL="http://$host:$MAILPIT_PORT"
  export APP_URL="$DEMO_URL" BETTER_AUTH_URL="$DEMO_URL"
  export AUTH_TRUSTED_ORIGINS="http://localhost:$PORT,http://127.0.0.1:$PORT"
}

port_in_use() {
  # Our own demo containers may already hold the ports – that is fine.
  if [ -n "$("${COMPOSE[@]}" ps --status running -q 2>/dev/null)" ]; then
    return 1
  fi
  if command -v lsof >/dev/null 2>&1; then
    lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1
  else
    (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null
  fi
}

wait_for_app() {
  printf 'Warte auf die App '
  for _ in $(seq 1 90); do
    if curl -fsS -o /dev/null "http://localhost:$PORT/api/health" 2>/dev/null; then
      printf ' bereit.\n'
      return 0
    fi
    printf '.'
    sleep 2
  done
  printf '\n'
  fail "Die App antwortet nicht. Log ansehen mit: bash scripts/demo.sh logs"
}

demo_people_count() {
  "${COMPOSE[@]}" exec -T db psql -U app -d wirwollenweg -tAc \
    "select count(*) from \"user\" where email like '%@demo.test'" 2>/dev/null | tr -d '[:space:]' || true
}

print_urls() {
  local phone
  if [ "$(env_value DEMO_BIND_ADDRESS)" = "127.0.0.1" ]; then
    phone="aus – nur am Laptop erreichbar (DEMO_BIND_ADDRESS=127.0.0.1)"
  elif [[ "$DEMO_URL" == http://localhost* ]]; then
    phone="nicht möglich – keine WLAN-Adresse gefunden"
  else
    phone="$DEMO_URL
  Codes am Handy: $MAIL_URL"
  fi
  cat <<EOF

------------------------------------------------------------------
  Wir wollen weg – Demo läuft

  Am Laptop:      http://localhost:$PORT
  Login-Codes:    http://localhost:$MAILPIT_PORT   (Mailpit – hier kommen alle Mails an)

  Handy (gleiches WLAN):
                  $phone

  Demo-Login:     anna@demo.test (Code aus Mailpit)
  Stoppen:        bash scripts/demo.sh stop
------------------------------------------------------------------
EOF
}

# The database volume outlives .env.demo (deleted file, fresh ZIP download in another folder):
# its password would no longer match. Inside the container the socket login needs no
# password, so set it to the current value on every start. Alphanumeric – no quoting issues.
sync_db_password() {
  local pw
  pw=$(env_value POSTGRES_PASSWORD)
  [[ "$pw" =~ ^[A-Za-z0-9]+$ ]] || fail "POSTGRES_PASSWORD in $ENV_FILE darf nur Buchstaben und Ziffern enthalten."
  "${COMPOSE[@]}" exec -T db psql -U app -d wirwollenweg -q -c "alter user app with password '$pw'" >/dev/null
}

cmd_start() {
  check_docker
  create_env_file
  configure_urls
  for p in $PORT $MAILPIT_PORT; do
    if port_in_use "$p"; then
      fail "Port $p ist schon belegt (läuft noch ein anderes Programm oder eine alte Demo?). Siehe Anleitung, Abschnitt Fehlerbehebung."
    fi
  done
  say "Baue und starte die Demo (beim ersten Mal 5–10 Minuten)"
  "${COMPOSE[@]}" up -d --build
  say "Datenbank vorbereiten"
  sync_db_password
  "${COMPOSE[@]}" run --rm tools pnpm db:migrate
  echo
  if [ "$(demo_people_count)" = "0" ]; then
    say "Demo-Daten einspielen (Anna, Ben, Carla … und ihre Reisen)"
    "${COMPOSE[@]}" run --rm tools pnpm db:seed:demo >/dev/null
  fi
  wait_for_app
  print_urls
}

cmd_seed() {
  check_docker
  [ -f "$ENV_FILE" ] || fail "Die Demo wurde noch nie gestartet. Erst: bash scripts/demo.sh start"
  configure_urls
  say "Setze die Demo-Personen und -Reisen zurück"
  "${COMPOSE[@]}" run --rm tools pnpm db:seed:demo >/dev/null
  clear_limits
  echo "Fertig. Alle Personen @demo.test (auch selbst angelegte) und ihre Reisen sind wie neu."
}

# Sign-in limits (5 code mails per address and hour, IP limits) are stored in the database.
# In a demo one address is used over and over – this clears them. Never for production.
clear_limits() {
  [ "$(env_value APP_ENV)" = "demo" ] || fail "unlock ist nur für die Demo gedacht (APP_ENV=demo)."
  "${COMPOSE[@]}" exec -T db psql -U app -d wirwollenweg -q -c \
    "delete from auth_attempt; delete from rate_limit; delete from rate_limit_event;" >/dev/null
}

cmd_unlock() {
  check_docker
  [ -f "$ENV_FILE" ] || fail "Die Demo wurde noch nie gestartet. Erst: bash scripts/demo.sh start"
  configure_urls
  clear_limits
  echo "Anmelde-Sperren aufgehoben – du kannst sofort neue Codes anfordern."
}

cmd_stop() {
  check_docker
  say "Stoppe die Demo (Daten bleiben erhalten)"
  if [ -f "$ENV_FILE" ]; then
    configure_urls
    "${COMPOSE[@]}" down
  else
    compose_without_env down
  fi
}

cmd_reset() {
  check_docker
  say "Lösche die Demo komplett (Datenbank und Mails)"
  compose_without_env down -v --remove-orphans
  echo "Fertig. Neu starten mit: bash scripts/demo.sh start"
}

cmd_status() {
  check_docker
  [ -f "$ENV_FILE" ] || fail "Die Demo wurde noch nie gestartet. Erst: bash scripts/demo.sh start"
  configure_urls
  "${COMPOSE[@]}" ps
  print_urls
}

cmd_logs() {
  check_docker
  configure_urls
  "${COMPOSE[@]}" logs -f --tail 100 app
}

case "${1:-start}" in
  start | up) cmd_start ;;
  stop | down) cmd_stop ;;
  seed) cmd_seed ;;
  unlock) cmd_unlock ;;
  reset) cmd_reset ;;
  status) cmd_status ;;
  logs) cmd_logs ;;
  -h | --help | help) sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) fail "Unbekannter Befehl '$1'. Möglich: start, stop, seed, unlock, reset, status, logs" ;;
esac
